import { test } from 'node:test'
import assert from 'node:assert/strict'

import { looksPlanning, stripLeakedThinking } from '../src/outbound.js'

/**
 * 2026-10-27 姐姐定：老三调工具前会把「下一步干什么」当正文发出去。
 * 下面的样本全部是 QQ 记录里的**原话**（`QQ会话/私聊_2710586329/聊天记录/2026-10-26.md`、
 * `2026-10-27.md`，以及 `QQ会话/logs/dsh-qq-2026-10-27.log` 里那几条 `→` 行），
 * 一条都没改字——测试要钉的就是真实发生过的东西。
 */

const REAL_LEAKS = [
  // 10-26 23:36:34 拆信之前
  '这是第二封？最近一封是20:55放的。门口挂着2封。让我看看目录里有什么。',
  // 05:39:12 写便签之前（流式切出来的第一句）
  '其实为了稳，先 glob 便签.md。让我在同一块里做 qq_send + glob。',
  // 05:39:17
  '更新便签。保留「更早记的」那几条？可以保留，但精简。三段为主。',
  // 05:39:17 末尾单独一行
  '写新的。',
  // 08:00:31 主动开口，想去拆信
  '我也可以顺便真去拆信？她睡着，没人打扰，合适做。但拆完再发一句更有料。要不要现在读？读信是允许的（门口提示说想看就读）。那我就读一封，然后发一句。',
  // 08:00:39
  '好，一句。发。',
  // 08:23:51 姐姐让她数门口几封信
  '用 glob 列门口目录下的 md 文件。刚才我知道：2026-10-26-2348-大姐.md，以及我写的 老三-2026-10-27.md。但可能还有别的信。便签里说「门口两封都拆了」，所以可能还有别的。',
  // 08:23:51 末尾单独一行（glob 的参数）
  '门口/*.md。',
  // 08:23:54 工具返回的条数
  '0',
  // 08:33:21 姐姐说「翻一下便签，就看看，不用做其他什么」之后——
  // 第一版规则一条都没拦住，姐姐当天早上就回了「没修完，还是有」。
  '注意「不用做其他什么」，所以只读不写。',
  // 08:33:21 同一轮的第二句，点的是 read 工具的参数
  '读 便签.md。',
  // 08:40:47 同一个动作换成英文，姐姐第二次说「不行做不到」时的那条
  '不用工具其他。read 便签.md。',
]

test('真实泄漏的句子一句都不许漏出去', () => {
  for (const line of REAL_LEAKS) {
    const out = stripLeakedThinking(line)
    const left = out.split(/(?<=[。！？!?…])/).map((s) => s.trim()).filter(Boolean)
    for (const s of left) {
      assert.equal(looksPlanning(s), false, `还剩 planning：${s} ← 原文 ${line}`)
    }
  }
})

test('整段清洗后只剩真正要说的话', () => {
  // 05:39 那三轮：两条 planning + 一条正文
  const raw = [
    '其实为了稳，先 glob 便签.md。让我在同一块里做 qq_send + glob。',
    '更新便签。保留「更早记的」那几条？可以保留，但精简。三段为主。',
    '写好了，便签换成今晚的：群 @ 那件事、两个群词典还空着、还有那碗白饭',
  ].join('\n')
  assert.equal(
    stripLeakedThinking(raw),
    '写好了，便签换成今晚的：群 @ 那件事、两个群词典还空着、还有那碗白饭',
  )
})

test('拆信那轮：正文留得住，打算留不住', () => {
  const raw = [
    '我也可以顺便真去拆信？她睡着，没人打扰，合适做。但拆完再发一句更有料。要不要现在读？那我就读一封，然后发一句。',
    '好，一句。发。',
    '信也回了，搁在门口',
  ].join('\n')
  assert.equal(stripLeakedThinking(raw), '信也回了，搁在门口')
})

test('数信那轮：glob 和参数都不出去', () => {
  const raw = [
    '用 glob 列门口目录下的 md 文件。刚才我知道：2026-10-26-2348-大姐.md，以及我写的 老三-2026-10-27.md。但可能还有别的信。',
    '门口/*.md。',
    '0',
    '三封都拆完了，刚那封是最后一封',
  ].join('\n')
  assert.equal(stripLeakedThinking(raw), '三封都拆完了，刚那封是最后一封')
})

/**
 * 反面：她真会对姐姐说的话，一个字都不许删。
 * 这些是从当天聊天记录里挑的正常句子，以及「让我…」里最容易误伤的那几种。
 */
const REAL_TALK = [
  '让我想想',
  '让我读给你听',
  '让我看看你今天怎么样',
  '那我就不发了',
  '要不要一起吃白饭',
  '我先去忙了',
  '写好了',
  '我写好了，便签换了',
  '真的呀，尾巴都摇起来了',
  '那本姑娘就在这儿呀，没跑',
  '读得动，两个群那本我都能翻开，不过都还是空表头，一个词都没填',
  '急着也急不出七天前的记录呀',
  '信也回了，搁在门口',
  '我读了你写的 2026-10-27.md',
]

test('正常说话不许误伤', () => {
  for (const line of REAL_TALK) {
    assert.equal(looksPlanning(line), false, `误伤了正常话：${line}`)
    assert.equal(stripLeakedThinking(line), line, `正常话被改掉了：${line}`)
  }
})
